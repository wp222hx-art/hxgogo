test('enumerated universes match independent arithmetic and preserve combination semantics', () => {
  assert.equal(core.candidateSpace(digits3),10*10*10)
  assert.equal(core.candidateSpace(digits5),10*10*10*10*10)
  const eleven = [...core.enumerateCandidates(eleven5)]
  assert.equal(eleven.length,462)
  assert.equal(new Set(eleven.map(x=>x.join(','))).size,462)
  assert.deepEqual(eleven[0],[1,2,3,4,5])
  assert.deepEqual(eleven.at(-1),[7,8,9,10,11])
  assert.ok(eleven.every(a => a.every((n,i) => !i || n > a[i-1])))
  let frontCount=0,frontContainingOne=0,last
  for (const numbers of core.enumerateCandidates(front)) { frontCount++;if(numbers.includes(1))frontContainingOne++;last=numbers }
  assert.equal(frontCount,324632)
  assert.equal(frontContainingOne,46376) // choose the remaining four from 34 independently
  assert.deepEqual(last,[31,32,33,34,35])
  const backCount=[...core.enumerateCandidates(back)].length
  assert.equal(backCount,66)
  assert.equal(frontCount*backCount,21425712)
  assert.equal(core.candidateSpace({min:1,max:3,count:2,ordered:false,replacement:true}),6)
  assert.deepEqual([...core.enumerateCandidates({min:1,max:3,count:2,ordered:false,replacement:true})],[[1,1],[1,2],[1,3],[2,2],[2,3],[3,3]])
  assert.equal([...core.enumerateCandidates({min:1,max:3,count:2,ordered:true,replacement:false})].length,6)
  assert.throws(()=>core.evaluateCandidates({...digits3,count:6}),/过大|50万/)
})

test('screenshot 500 then 256 candidates, inverse and tolerance obey set arithmetic', () => {
  const oddFirst={metricId:'position:0',values:[1,3,5,7,9],minHits:1,maxHits:1}
  const noZeroOrFive={metricId:'numbers',values:[0,5],minHits:0,maxHits:0}
  assert.equal(core.evaluateCandidates(digits3,[oddFirst]).count,500)
  const rules=[oddFirst,noZeroOrFive]
  assert.equal(core.evaluateCandidates(digits3,rules).count,256) // 4 first choices × 8 × 8
  assert.equal(core.evaluateCandidates(digits3,rules,{inverse:true}).count,744)
  assert.equal(core.evaluateCandidates(digits3,rules,{globalTolerance:1}).count,756) // union: 500 + 512 - 256
  assert.equal(core.evaluateCandidates(digits3,[{metricId:'numbers',values:[0,5],minHits:1,maxHits:1,tolerance:1}]).count,992) // reject only 2³ triples entirely from {0,5}
  assert.equal(core.evaluateCandidates(digits3,[{...noZeroOrFive,exclude:true}]).count,488)
  const page=core.evaluateCandidates(digits3,[],{page:2,pageSize:100})
  assert.deepEqual(page.items[0].numbers,[1,0,0])
  assert.deepEqual(page.items.at(-1).numbers,[1,9,9])
})

test('known gaps and unknown observations never inflate consecutive counts or positional omissions', () => {
  assert.equal(core.omissionStats([true,null,true]).maxStreak,1)
  assert.equal(core.omissionStats([false,null,false]).maxMiss,1)
  assert.equal(core.omissionStats([false,null]).currentMiss,null)
  assert.equal(core.omissionStats([true,null,true]).observed,2)
  const records=[
    {period:'p1',numbers:[1,0,0],previousContiguous:null},
    {period:'p2',numbers:[2,0,0],previousContiguous:true},
    {period:'p4',numbers:[3,0,0],previousContiguous:false},
    {period:'p5',numbers:[2,0,0],previousContiguous:true},
  ]
  const trend=core.buildTrend(records,['sumAmplitude','positionOmission:0'],digits3)
  assert.equal(at(trend,0,'sumAmplitude',1).hit,null)
  assert.equal(at(trend,1,'sumAmplitude',1).hit,true)
  assert.equal(at(trend,2,'sumAmplitude',1).hit,null)
  assert.equal(at(trend,2,'positionOmission:0',1).hit,null)
  assert.equal(at(trend,3,'positionOmission:0',1).hit,true)
  const basic=core.buildTrend([
    {period:'p1',numbers:[1,0,0],previousContiguous:null},
    {period:'p3',numbers:[1,0,0],previousContiguous:false},
  ],['sum'],digits3)
  const sumOne=basic.columns.findIndex(c=>c.value===1)
  assert.equal(basic.stats[sumOne].count,2)
  assert.equal(basic.stats[sumOne].maxStreak,1)
  assert.equal(at(basic,1,'sum',2).miss,1)
})

test('long positional omissions use the documented >=300 bucket instead of losing the hit', () => {
  const history=Array.from({length:400},(_,i)=>({period:'p'+i,numbers:[1,0,0],previousContiguous:i?true:null}))
  const values=metric('positionOmission:0',[2,0,0],null,digits3,{historyBefore:history})
  assert.deepEqual(values,[300])
  const trend=core.buildTrend([...history,{period:'last',numbers:[2,0,0],previousContiguous:true}],['positionOmission:0'],digits3)
  assert.equal(at(trend,400,'positionOmission:0',300).hit,true)
  assert.match(core.metricCatalog(digits3).find(m=>m.id==='positionOmission:0').definition,/300/)
})

test('without-replacement amplitude uses the actual sum range and subset observations count once', () => {
  assert.deepEqual(metric('amplitudeAttr',[3,5,8,9,10],[1,2,3,4,5],eleven5),['双','大','合','2路'])
  const anyTwo={...eleven5,count:2}
  const history=[
    {period:'p1',numbers:[1,2,3,4,5],previousContiguous:null},
    {period:'p2',numbers:[2,3,4,5,6],previousContiguous:true},
  ]
  const trend=core.buildTrend(history,['sum','sumAmplitude'],anyTwo)
  assert.equal(trend.rows.length,2)
  assert.equal(at(trend,0,'sum',3).hit,true)
  assert.equal(at(trend,0,'sum',9).hit,true)
  assert.equal(at(trend,0,'sum',15).hit,false)
  const sumSeven=trend.columns.findIndex(c=>c.metricId==='sum'&&c.value===7)
  assert.equal(trend.stats[sumSeven].count,2) // multiple pairs total seven; each draw contributes one hit
  assert.equal(trend.stats[sumSeven].observed,2)
  assert.equal(at(trend,1,'sumAmplitude',1).hit,null)
  const condition={metricId:'numberSet',values:['01,05'],minHits:1,maxHits:1}
  assert.equal(core.matchesRules([1,2,3,4,5],[condition],anyTwo).accepted,true)
  assert.equal(core.matchesRules([2,3,4,5,6],[condition],anyTwo).accepted,false)
  assert.equal(core.matchesRules([1,5],[condition],anyTwo,{inverse:true}).accepted,false)
  assert.equal(core.matchesRules([1,2,3,4,5],[condition],anyTwo,{inverse:true}).accepted,true)
  const ranked=core.evaluateCandidates(anyTwo,[condition],{history:[history[0]],order:'score'})
  assert.equal(ranked.count,1)
  assert.equal(ranked.items[0].score,100)
  assert.match(ranked.definition,/不是命中概率/)
})

test('all reachable values fit their declared metric domains on exhaustive small universes', () => {
  for (const rule of [digits3,eleven5]) {
    const catalog=core.metricCatalog(rule)
    for (const nums of core.enumerateCandidates(rule)) {
      for (const entry of catalog) {
        if(entry.id==='numberSet')continue
        for (const value of metric(entry.id,nums,nums,rule)) {
          assert.ok(entry.values.includes(value),entry.id+' omitted '+value+' for '+nums.join(','))
        }
      }
    }
  }
  for (const nums of [[1,2,3,4,5],[31,32,33,34,35],[1,2,3,34,35],[1,9,17,26,35]]) {
    for (const entry of core.metricCatalog(front)) {
      if(entry.id==='numberSet')continue
      for (const value of metric(entry.id,nums,nums,front)) assert.ok(entry.values.includes(value),entry.id+' omitted '+value)
    }
  }
})

