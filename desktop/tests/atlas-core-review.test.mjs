import { test } from 'node:test'
import assert from 'node:assert/strict'
import * as core from '../../public/static/atlas-core.js'

const digits3 = { min:0,max:9,count:3,ordered:true,replacement:true }
const digits5 = { ...digits3,count:5 }
const eleven5 = { min:1,max:11,count:5,ordered:false,replacement:false }
const front = { ...eleven5,max:35 }
const back = { ...eleven5,max:12,count:2 }
const metric = (id, numbers, previous = null, rule = digits3, params = {}) => core.metricValues(id,numbers,previous,rule,params)
const at = (trend, row, metricId, value) => {
  const i = trend.columns.findIndex(c => c.metricId === metricId && c.value === value)
  assert.ok(i >= 0, 'missing metric column ' + metricId + '=' + value)
  return trend.rows[row].cells[i]
}

