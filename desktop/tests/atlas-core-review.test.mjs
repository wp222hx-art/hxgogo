test('invalid history cannot dilute scores, oversized observation subsets are bounded, and unknown rules stay unknown', () => {
  const selected={metricId:'numberSet',values:['1,2,3']}
  const result=core.evaluateCandidates(digits3,[selected],{history:[{numbers:[1,2,3]},{numbers:[99]}]})
  assert.equal(result.count,1)
  assert.equal(result.items[0].score,100)
  const many=Array.from({length:49},(_,i)=>i+1)
  const rule={min:1,max:49,count:5,ordered:false,replacement:false}
  assert.throws(()=>core.buildTrend([{period:'p1',numbers:many}],['sum'],rule),/50万|观察范围/)
  assert.throws(()=>core.matchesRules(many,[],rule),/50万|观察范围/)
  const missingPrevious={metricId:'sumAmplitude',values:[1],minHits:1,maxHits:1}
  for(const options of [{inverse:true},{globalTolerance:2},{inverse:true,globalTolerance:2}]) {
    const outcome=core.matchesRules([1,2,3],[missingPrevious],digits3,options)
    assert.equal(outcome.known,false)
    assert.equal(outcome.accepted,false)
  }
})


